// Georgian words the reports already use (weather, causes, trades, statuses).
const DICT = new Map(Object.entries({ ...KA, ...KA_UI }).map(([en, ka]) => [en.trim(), ka]));

/** The Georgian for one piece of English text, or null when there is none. */
export function translate(text) {
  const key = text.replace(/\s+/g, ' ').trim();
  if (!key || !/[A-Za-z]/.test(key)) return null;
  const hit = DICT.get(key);
  if (hit != null) return hit;
  if (key.length > 400) return null;
  const joined = key.includes(' · ');
  for (const [re, to] of PATTERNS) {
    // A line of "A · B" pieces is taken whole only by a pattern written for one.
    if (joined && !re.source.includes('·')) continue;
    if (re.test(key)) return key.replace(re, to);
  }
  // "A · B · C" or several sentences: each piece on its own, as far as it is known.
  const pieces = key.includes(' · ') ? key.split(' · ')
    : /[.!?] [A-Z]/.test(key) ? key.split(/(?<=[.!?]) (?=[A-Z])/) : null;
  if (pieces && pieces.length > 1) {
    const done = pieces.map((p) => translate(p) ?? p);
    if (done.some((p, i) => p !== pieces[i])) return done.join(key.includes(' · ') ? ' · ' : ' ');
  }
  return null;
}

// ---------- Applying it to the page ----------
const SKIP = '.rpt, .pdf-page, #pdf-export-root, [data-no-i18n], script, style, textarea, [contenteditable]';
// A text box's placeholder is the app's; only what is typed in it is the person's.
const SKIP_ATTRS = '.rpt, .pdf-page, #pdf-export-root, [data-no-i18n]';
const ATTRS = ['placeholder', 'title', 'aria-label'];

function translateText(node) {
  const parent = node.parentElement;
  if (!parent || parent.closest(SKIP)) return;
  const raw = node.nodeValue;
  const ka = translate(raw);
  if (ka == null || ka === raw.trim()) return;
  const lead = raw.match(/^\s*/)[0];
  const trail = raw.match(/\s*$/)[0];
  node.nodeValue = lead + ka + trail;
}

function translateAttrs(el) {
  if (el.closest(SKIP_ATTRS)) return;
  for (const a of ATTRS) {
    const v = el.getAttribute(a);
    if (!v) continue;
    const ka = translate(v);
    if (ka != null && ka !== v) el.setAttribute(a, ka);
  }
}

function translateTree(root) {
  if (root.nodeType === 3) return translateText(root);
  if (root.nodeType !== 1) return;
  if (root.closest?.(SKIP_ATTRS)) return;
  translateAttrs(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeType === 3) translateText(n);
    else translateAttrs(n);
  }
}

/** In Georgian: translates the page now and whatever is drawn on it later. */
export function startTranslating() {
  if (!isKa) return;
  document.documentElement.lang = 'ka';
  translateTree(document.body);
  new MutationObserver((records) => {
    for (const r of records) {
      if (r.type === 'childList') r.addedNodes.forEach(translateTree);
      else if (r.type === 'attributes') translateAttrs(r.target);
      else if (r.type === 'characterData') translateText(r.target);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });

  // The browser's own boxes (confirm, prompt, alert) get their text translated too.
  for (const name of ['alert', 'confirm', 'prompt']) {
    const native = window[name].bind(window);
    window[name] = (message, ...rest) => native(translate(String(message ?? '')) ?? message, ...rest);
  }
}
