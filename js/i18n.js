const LANG_KEY = 'cpm.lang';
export const lang = (() => {
  try { return localStorage.getItem(LANG_KEY) === 'ka' ? 'ka' : 'en'; } catch { return 'en'; }
})();
export const isKa = lang === 'ka';
/** The locale dates are written in. */
export const dateLocale = isKa ? 'ka-GE' : undefined;

/** Switches language: remembered in this browser, and the page drawn again in it. */
export function setLang(next) {
  try { localStorage.setItem(LANG_KEY, next); } catch { /* storage unavailable: this visit only */ }
  location.reload();
}

